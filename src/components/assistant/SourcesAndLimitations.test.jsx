import { describe, it, expect } from 'vitest';
import { renderToStaticMarkup } from 'react-dom/server';
import SourcesAndLimitations from './SourcesAndLimitations';
import { buildSourcePanelModel } from './sourcePanelModel';

const LONG_URL = 'https://example.gov.in/' + 'very-long-path-segment/'.repeat(10);

const withSources = {
  data: {
    disclaimer: 'Rules may vary by municipality.',
    officialSources: [
      { name: 'Passport Seva', url: 'https://www.passportindia.gov.in/', lastVerified: '2024-03-05' },
    ],
  },
  retrievedChunks: [
    { sectionTitle: 'Fees', excerpt: 'The fee is fixed.', sourceName: 'Passport Seva', lastVerified: '2024-03-05' },
  ],
};

const render = (message, props = {}) =>
  renderToStaticMarkup(<SourcesAndLimitations message={message} {...props} />);

describe('SourcesAndLimitations', () => {
  it('renders nothing when the message has no source data', () => {
    expect(render({ text: 'hello' })).toBe('');
    expect(render({ data: { officialSources: [] }, retrievedChunks: [] })).toBe('');
    expect(render(undefined)).toBe('');
  });

  it('is collapsed by default with an accessible toggle', () => {
    const html = render(withSources);
    expect(html).toContain('aria-expanded="false"');
    expect(html).toContain('aria-controls=');
    expect(html).toContain('Sources and limitations (2)');
    expect(html).toMatch(/class="sources-panel__body"[^>]*hidden/);
  });

  it('shows sources, excerpts, dates and disclaimer when open', () => {
    const html = render(withSources, { defaultOpen: true });
    expect(html).toContain('aria-expanded="true"');
    expect(html).toContain('href="https://www.passportindia.gov.in/"');
    expect(html).toContain('rel="noopener noreferrer"');
    expect(html).toContain('target="_blank"');
    expect(html).toContain('Passport Seva');
    expect(html).toContain('(opens in a new tab)');
    expect(html).toContain('Official source excerpts');
    expect(html).toContain('The fee is fixed.');
    expect(html).toContain('Last verified: March 5, 2024');
    expect(html).toContain('Rules may vary by municipality.');
    expect(html).toContain('generated by the assistant from the official excerpts');
  });

  it('marks missing metadata as unavailable without inventing values', () => {
    const html = render(
      { data: { officialSources: [{ name: 'Some Portal', url: 'not a url' }, { url: 'https://a.gov.in/' }] } },
      { defaultOpen: true },
    );
    expect(html).toContain('Link unavailable');
    expect(html).toContain('Unnamed source');
    expect(html).toContain('Review date unavailable');
    expect(html).not.toContain('Last verified:');
    expect(html).not.toContain('href="not a url"');
    expect(html).toContain('not quoted from an official document');
  });

  it('does not link javascript: URLs', () => {
    const html = render({ data: { officialSources: [{ name: 'Bad', url: 'javascript:alert(1)' }] } }, { defaultOpen: true });
    expect(html).not.toContain('href=');
    expect(html).toContain('Link unavailable');
  });

  it('renders long URLs in full inside a wrapping element', () => {
    const html = render({ data: { officialSources: [{ name: 'Long', url: LONG_URL }] } }, { defaultOpen: true });
    expect(html).toContain('class="sources-panel__url"');
    expect(html).toContain(LONG_URL);
  });
});

describe('buildSourcePanelModel', () => {
  it('ignores blank excerpts and non-object sources', () => {
    const model = buildSourcePanelModel({
      data: { officialSources: [null, 'x'] },
      retrievedChunks: [{ excerpt: '   ' }, null],
    });
    expect(model.hasContent).toBe(false);
  });

  it('falls back to section type for the excerpt title', () => {
    const model = buildSourcePanelModel({ retrievedChunks: [{ sectionType: 'fees', excerpt: 'x' }] });
    expect(model.excerpts[0].title).toBe('fees');
    expect(model.excerpts[0].lastVerified).toBeNull();
  });
});
