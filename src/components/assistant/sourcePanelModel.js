import { inspectOfficialSource, formatVerificationDate } from '../../services/sourceVerificationService';

const clean = (value) => (typeof value === 'string' ? value.trim() : '');

/**
 * Builds the view model for the "Sources and limitations" panel from the
 * data an assistant message actually carries. Nothing is invented: a missing
 * name, link or review date is reported as unavailable.
 *
 * @param {Object} msg - assistant message ({ data, retrievedChunks, ... })
 * @returns {{ hasContent: boolean, sources: Array, excerpts: Array, disclaimer: string, limitation: string }}
 */
export function buildSourcePanelModel(msg) {
  const data = msg?.data || {};
  const rawSources = Array.isArray(data.officialSources) ? data.officialSources : [];
  const rawChunks = Array.isArray(msg?.retrievedChunks) ? msg.retrievedChunks : [];

  const sources = rawSources
    .filter((src) => src && typeof src === 'object')
    .map((src) => {
      const inspected = inspectOfficialSource(src);
      return {
        name: clean(src.name) || 'Unnamed source',
        url: inspected.isValid ? inspected.cleanUrl : '',
        domain: inspected.domain,
        lastVerified: formatVerificationDate(src.lastVerified),
      };
    });

  const excerpts = rawChunks
    .filter((chunk) => chunk && clean(chunk.excerpt))
    .map((chunk) => ({
      title: clean(chunk.sectionTitle) || clean(chunk.sectionType) || 'Source section',
      excerpt: clean(chunk.excerpt),
      sourceName: clean(chunk.sourceName),
      lastVerified: formatVerificationDate(chunk.lastVerified),
    }));

  const hasExcerpts = excerpts.length > 0;
  return {
    hasContent: sources.length > 0 || hasExcerpts,
    sources,
    excerpts,
    disclaimer: clean(data.disclaimer),
    limitation: hasExcerpts
      ? 'The summary above is generated by the assistant from the official excerpts listed here.'
      : 'This answer was written by the assistant and is not quoted from an official document.',
  };
}
