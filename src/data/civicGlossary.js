export const findJargonTerms = (text = '') => {
  if (!text) return [];
  const lower = text.toLowerCase();
  return CIVIC_GLOSSARY.filter((item) => lower.includes(item.term.toLowerCase()) || lower.includes(item.id));
};

export const searchGlossary = (query = '') => {
  if (!query.trim()) return CIVIC_GLOSSARY;
  const q = query.toLowerCase().trim();
  return CIVIC_GLOSSARY.filter((item) => {
    return (
      item.term.toLowerCase().includes(q) ||
      item.simpleMeaning.toLowerCase().includes(q) ||
      item.hiTerm?.toLowerCase().includes(q) ||
      item.context.toLowerCase().includes(q)
    );
  });
};
